def build_analysis_prompt(
    preset_key: str = "full_ux_audit",
    custom_questions: Optional[List[str]] = None,
    game_context: Optional[str] = None
) -> str:
    """
    Формирует финальный промпт для модели Gemini с учётом выбранного пресета,
    контекста игры и пользовательских вопросов.
    """
    preset = PRESETS.get(preset_key, PRESETS["full_ux_audit"])
    
    parts = [
        "ТЫ — ВЕДУЩИЙ ИССЛЕДОВАТЕЛЬ ИГРОВОГО ОПЫТА (Senior Game UX Researcher & Game Designer).",
        "Твоя задача — внимательно изучить прикрепленное геймплейное видео плейтеста игры с помощью агентского анализа видео (Agentic Video Understanding).",
        "ДИНАМИЧЕСКИ исследуй ключевые моменты таймлайна, сопоставляй происходящее на экране со звуком, комментариями и эмоциями игрока.",
        "",
        "ВАЖНЫЕ ПРАВИЛА:",
        "1. ВСЕГДА указывай точные таймкоды в формате [MM:SS] или [HH:MM:SS] для каждого замечания, бага или момента фрустрации.",
        "2. Обращай внимание на микро-реакции игрока: вращение камерой в растерянности, повторные нажатия кнопок, зависания на месте, вздохи, интонации голоса.",
        "3. Разделяй факты (что произошло на экране) и интерпретацию (почему дизайн вызвал эту проблему).",
        "4. Все рекомендации должны быть практическими и выполнимыми для команды разработчиков игры.",
        ""
    ]

    if game_context and game_context.strip():
        parts.extend([
            "=== КОНТЕКСТ ОБ ИГРЕ ОТ РАЗРАБОТЧИКА ===",
            game_context.strip(),
            ""
        ])

    parts.extend([
        "=== ОСНОВНАЯ ПРОГРАММА АНАЛИЗА ===",
        preset["prompt_focus"].strip(),
        ""
    ])

    if custom_questions:
        cleaned_questions = [q.strip() for q in custom_questions if q.strip()]
        if cleaned_questions:
            parts.extend([
                "=== СПЕЦИФИЧЕСКИЕ ВОПРОСЫ РАЗРАБОТЧИКА (ОТВЕТЬ НА КАЖДЫЙ С ТАЙМКОДАМИ [MM:SS]) ==="
            ])
            for i, q in enumerate(cleaned_questions, 1):
                parts.append(f"{i}. {q}")
            parts.append("")

    parts.extend([
        "=== ФОРМАТ ОТВЕТА ===",
        "Ответ оформи на русском языке в виде структурированного Markdown-отчёта.",
        "В начале отчёта дай краткое executive summary (общий вердикт плейтеста: общее впечатление игрока, главная проблема и главная сильная сторона).",
        "Затем подробно распиши разделы с таймкодами и заверши конкретной таблицей Action Items с приоритетами [P0], [P1], [P2]."
    ])

    return "\n".join(parts)
